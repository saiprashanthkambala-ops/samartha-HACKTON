export function getCrop(id) {
  return crops.find((c) => c.id === id) || null;
}

export function cropsByCategory(category) {
  return category === 'all' ? crops : crops.filter((c) => c.category === category);
}

export function searchCrops(query) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return crops;
  return crops.filter(
    (c) => c.id.includes(q) || c.keywords.some((k) => k.toLowerCase().includes(q)),
  );
}

